#!/usr/bin/env node
// Pattern pack conformance runner for the TypeScript runtime.
//
//   node scripts/conformance.mjs           run every case in pack/conformance,
//                                          write conformance/typescript.json,
//                                          exit 1 unless passed == cases
//   node scripts/conformance.mjs --seed    regenerate the corpus-derived case
//                                          files (pack/conformance/
//                                          <class>-cases.jsonl) from bench/corpus,
//                                          with expectations taken from this
//                                          runtime
//
// The record carries packSha256 so a release can refuse to publish when the
// record was produced against a different pack than the one it embeds; that
// check is scripts/release-gate.mjs (npm run release:gate). `npm publish` runs
// this runner and then that check through the prepublishOnly script.
// regressions.jsonl is written by hand and is never touched by --seed.
//
// Every seeded case carries `fixture: SEEDED_FIXTURE_NOTE`. The corpus text is
// generated by bench/generate.mjs and includes token-shaped strings (AKIA...,
// sk-..., ghp_...) that are not credentials; the note names them as FAKE on the
// same line so a credential scan over the file can tell them from a leak.
// Both runtimes' loaders ignore the key.
//
// Requires a build: npm run build.

import { mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createRequire } from 'node:module';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const CASES_DIR = resolve(ROOT, 'pack/conformance');
const CORPUS_DIR = resolve(ROOT, 'bench/corpus');
const RECORD_PATH = resolve(ROOT, 'conformance/typescript.json');

const require = createRequire(import.meta.url);
const { conformanceOutcome, runConformance } = require(resolve(ROOT, 'dist/conformance.js'));

const SEEDED_FIXTURE_NOTE = 'FAKE synthetic value generated by bench/generate.mjs, not a credential';

// Every case file is named <class>-cases.jsonl. A bare class name such as
// `credential`, `secrets` or `passwords` reads as a credential store to
// secret-file name rules, which refuse such a file on sight whatever it holds;
// the suffix keeps every class, present or future, clear of them. Both loaders
// read every *.jsonl in the directory and key on the embedded id.
const caseFileName = (klass) => `${klass}-cases.jsonl`;

if (process.argv.includes('--seed')) {
  for (const file of readdirSync(CORPUS_DIR).filter((f) => f.endsWith('.jsonl')).sort()) {
    const klass = file.replace(/\.jsonl$/, '');
    const records = readFileSync(resolve(CORPUS_DIR, file), 'utf8')
      .split('\n')
      .filter((l) => l.length > 0)
      .map((l) => JSON.parse(l));
    const lines = records.map((rec, i) =>
      JSON.stringify({
        id: `${klass}-${String(i + 1).padStart(4, '0')}`,
        input: rec.text,
        expect: conformanceOutcome(rec.text),
        origin: `bench/corpus/${file}:${i + 1}`,
        fixture: SEEDED_FIXTURE_NOTE,
      }),
    );
    const out = caseFileName(klass);
    writeFileSync(resolve(CASES_DIR, out), lines.join('\n') + '\n');
    console.log(`seeded pack/conformance/${out}: ${lines.length} cases`);
  }
  process.exit(0);
}

const record = runConformance(CASES_DIR);
mkdirSync(dirname(RECORD_PATH), { recursive: true });
writeFileSync(RECORD_PATH, JSON.stringify(record, null, 2) + '\n');

console.log(`runtime:    ${record.runtime} ${record.runtimeVersion}`);
console.log(`pack:       ${record.packVersion} sha256 ${record.packSha256}`);
console.log(`cases:      ${record.cases}`);
console.log(`passed:     ${record.passed}`);
for (const f of record.failures.slice(0, 20)) {
  console.log(`FAIL ${f.id}`);
  console.log(`  expect   ${JSON.stringify(f.expect)}`);
  console.log(`  actual   ${JSON.stringify(f.actual)}`);
}
if (record.failures.length > 20) console.log(`... ${record.failures.length - 20} more`);
console.log(`record:     conformance/typescript.json`);

process.exit(record.cases > 0 && record.passed === record.cases ? 0 : 1);
